class AssignmentExample {
    public static void main(String[] args) {
        
        int a = 10;
        
        a += 5;
        System.out.println("Now value of a is "+a);

        a -= 3;
        System.out.println("Now value of a is "+a);

        a *= 2;
        System.out.println("Now value of a is "+a);

        a /= 4;
        System.out.println("Now value of a is "+a);
    }
}